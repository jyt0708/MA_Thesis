def validate_and_filter_csvs(
    csv_files: Iterable[str | Path],
    target_column: str = TARGET_COLUMN,
    exists_column: str = EXISTS_COLUMN,
) -> dict[str, pd.DataFrame]:
    '''
    Validate required columns, keep rows for which Amount of Goods exists,
    convert the target to numeric, and align all files to shared columns.

    Extra columns are allowed, but the controlled three-file experiment uses
    only the intersection of columns.
    '''
    paths = [Path(path) for path in csv_files]
    if not paths:
        raise ValueError("No CSV files were provided.")

    raw_frames: list[pd.DataFrame] = []
    for path in paths:
        frame = read_csv(path)
        # print(f"Loaded {path.name}: {frame.columns}")
        missing = [
            column
            for column in (target_column, exists_column)
            if column not in frame.columns
        ]
        if missing:
            raise KeyError(f"{path.name} is missing required columns: {missing}")
        raw_frames.append(frame)

    common_set = set(raw_frames[0].columns)
    for frame in raw_frames[1:]:
        common_set.intersection_update(frame.columns)

    # Preserve the first file's column order.
    common_columns = [
        column for column in raw_frames[0].columns if column in common_set
    ]
    print(f"Using {len(common_columns)} columns shared by all {len(paths)} files.")

    filtered: dict[str, pd.DataFrame] = {}
    for path, frame in zip(paths, raw_frames):
        memory_stage("filtering CSV", report=True, file=path.name)
        frame = frame.loc[:, common_columns].copy()

        exists = pd.to_numeric(frame[exists_column], errors="coerce")
        frame = frame.loc[exists.eq(1)].copy()
        frame[target_column] = pd.to_numeric(
            frame[target_column], errors="coerce"
        )

        invalid = frame[target_column].isna()
        if invalid.any():
            examples = (
                frame.loc[invalid, target_column]
                .astype(str)
                .drop_duplicates()
                .head(10)
                .tolist()
            )
            raise ValueError(
                f"{path.name} contains missing/non-numeric {target_column} "
                f"values although {exists_column}=1. Examples: {examples}"
            )

        frame = frame.reset_index(drop=True)
        if len(frame) < 3:
            raise ValueError(
                f"{path.name} has only {len(frame)} valid target rows; at least 3 are required."
            )

        filtered[path.name] = frame
        print(f"{path.name}: {len(frame)} valid target observations")
        memory_stage("CSV filtered", report=True, rows=len(frame), columns=len(frame.columns))

    return filtered


