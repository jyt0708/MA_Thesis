# Custom LoRA layer
class LoRALinear(nn.Module):
  def __init__(
      self,
      base_layer: nn.Linear,
      rank=LORA_RANK,
      alpha=LORA_ALPHA,
      dropout=LORA_DROPOUT,
  ):
      super().__init__()

      self.base = base_layer
      self.rank = rank
      self.scale = alpha / rank
      self.dropout = nn.Dropout(dropout)
      device = base_layer.weight.device

      # Original layer is frozen
      for p in self.base.parameters():
          p.requires_grad = False

      # Lora weights should use FP32
      self.lora_A = nn.Linear(
          base_layer.in_features,
          rank,
          bias=False,
          device=device,
          dtype=torch.float32,
      )

      self.lora_B = nn.Linear(
          rank,
          base_layer.out_features,
          bias=False,
          device=device,
          dtype=torch.float32,
      )

      nn.init.kaiming_uniform_(
          self.lora_A.weight,
          a=np.sqrt(5),
      )

      nn.init.zeros_(
          self.lora_B.weight
      )

  def forward(self, x):
      base_output = self.base(x)
      lora_input = self.dropout(x).to(dtype=self.lora_A.weight.dtype)
      lora_output = self.lora_B(self.lora_A(lora_input))

      # convert adapter output back to base output dtype
      return base_output + self.scale * lora_output.to(dtype=base_output.dtype)



def inject_lora(
    model: nn.Module,
    rank: int = LORA_RANK,
    alpha: float = LORA_ALPHA,
    dropout: float = LORA_DROPOUT,
    target_names: tuple[str, ...] = ("query", "value"),
) -> list[str]:
    """
    Inject LoRA into the selected projections of cross-row and
    cross-column attention in all in-context encoder layers.
    The model is modified in place.

    Returns:
        Full names of all layers replaced with LoRALinear.
    """
    # Freeze all existing model parameters.
    for parameter in model.parameters():
        parameter.requires_grad = False

    replacements = []

    # Find the target projection layers.
    for module_name, module in model.named_modules():
        for child_name, child in module.named_children():
            full_name = (
                f"{module_name}.{child_name}"
                if module_name
                else child_name
            )

            is_attention_type = (
                "cross_row_layer.attention.self_attention" in full_name
                or
                "cross_column_layer.attention.self_attention" in full_name
            )

            is_target_projection = child_name in target_names

            if (
                is_attention_type
                and is_target_projection
                and isinstance(child, nn.Linear)
            ):
                replacements.append(
                    (module, child_name, child, full_name)
                )

    # Replace the selected linear projections.
    replaced_layer_names: list[str] = []

    for parent, child_name, child, full_name in replacements:
        setattr(
            parent,
            child_name,
            LoRALinear(
                base_layer=child,
                rank=rank,
                alpha=alpha,
                dropout=dropout,
            ),
        )

        replaced_layer_names.append(full_name)
        # print(f"LoRA injected: {full_name}")

    if not replaced_layer_names:
        raise RuntimeError(
            "No LoRA target layers were found. Check the model structure "
            "and target_names."
        )

    return replaced_layer_names


def trainable_parameters(model: nn.Module) -> list[nn.Parameter]:
    return [parameter for parameter in model.parameters() if parameter.requires_grad]


# Create a checkpoint containing only trainable LoRA parameters and store them to CPU
# Return dictionary primarily contain LoRA parameters such as the low-rank A and B matrices
def trainable_state_dict(model: nn.Module) -> dict[str, torch.Tensor]:
    return {
        name: parameter.detach().cpu().clone()
        for name, parameter in model.named_parameters()
        if parameter.requires_grad
    }


# Load the saved LoRA checkpoint into the existing model
def load_trainable_state_dict(
    model: nn.Module,
    state: dict[str, torch.Tensor],
) -> None:
    parameters = dict(model.named_parameters())
    missing = sorted(set(state) - set(parameters))
    if missing:
        raise KeyError(f"Adapter parameters missing from model: {missing}")

    # Overwrite model's parameters in-place with values from the checkpoint
    with torch.no_grad():
        for name, value in state.items():
            parameters[name].copy_(
                value.to(
                    device=parameters[name].device,
                    dtype=parameters[name].dtype,
                )
            )

"""### Tokenization, evaluation and training"""

def make_tokenizer(is_valid: bool) -> Tokenizer:
    return Tokenizer(
        regression_type="l2",
        classification_type="cross-entropy",
        random_seed=BASE_SEED,
        # num_regression_bins=16,
        is_valid=is_valid,
    )


def tokenize_episode(
    tokenizer: Tokenizer,
    episode: Episode,
    device: torch.device,
    model_dtype: torch.dtype,
    include_labels: bool,
) -> dict:
    # labels: real query values
    memory_stage(
        "tokenizing episode", context_rows=len(episode.X_context),
        query_rows=len(episode.X_query), columns=len(episode.X_context.columns),
    )
    data, labels, _ = tokenizer(
        episode.X_context,
        episode.y_context,
        episode.X_query,
        episode.y_query,
        "regression",
    )

    batch = {
        "data": data,
        "is_regression": torch.tensor(True),
    }

    # include labels during training, exclude during evaluation
    if include_labels:
        batch["labels"] = labels

    memory_stage("moving tokenized batch to device")
    return to_device(
        batch,
        device,
        dtype=model_dtype,
        raise_on_unexpected=False,
    )


def regression_metrics(
    y_true: np.ndarray,
    y_pred: np.ndarray,
) -> dict[str, float]:
    metrics = {
        "MAE": float(mean_absolute_error(y_true, y_pred)),
        "RMSE": float(root_mean_squared_error(y_true, y_pred)),
    }
    metrics["R2"] = (
        float(r2_score(y_true, y_pred)) if len(y_true) >= 2 else float("nan")
    )
    return metrics


@torch.no_grad()
def evaluate_episode(
    model: nn.Module,
    tokenizer: Tokenizer,
    episode: Episode,
    device: torch.device,
    model_dtype: torch.dtype,
) -> tuple[dict[str, float], np.ndarray]:
    model.eval()
    batch = tokenize_episode(
        tokenizer,
        episode,
        device,
        model_dtype,
        include_labels=False,
    )

    # In evaluation: output should be predictions
    memory_stage("evaluation forward")
    outputs = model(**batch)

    memory_stage("evaluation predictions and metrics")
    query_mask = batch["data"]["target"] <= -99
    # standardized_predictions = outputs[query_mask].float().cpu().numpy()
    standardized_predictions = (
        outputs[query_mask]
        .float()
        .cpu()
        .numpy()
        .reshape(-1)
    )

    # Train-only mean and std (no leakage)
    _, target_mean, target_std = tokenizer.standard_scale_column(
        episode.y_context,
        episode.y_query,
    )

    # un-standardize to get real world predicitons
    predictions = (standardized_predictions * float(target_std) + float(target_mean))
    predictions = np.asarray(predictions,dtype=float,).reshape(-1)

    true_values = (episode.y_query.iloc[:, 0].to_numpy(dtype=float).reshape(-1))

    # validate
    if len(predictions) != len(true_values):
      raise ValueError(
          "Prediction/target length mismatch: "
          f"predictions.shape={predictions.shape}, "
          f"true_values.shape={true_values.shape}, "
          f"outputs.shape={tuple(outputs.shape)}, "
          f"query_mask.shape={tuple(query_mask.shape)}"
      )

    return (regression_metrics(true_values, predictions), predictions)


def evaluate_episode_group(
    model: nn.Module,
    tokenizer: Tokenizer,
    episodes: dict[str, Episode],
    device: torch.device,
    model_dtype: torch.dtype,
) -> tuple[
    dict[str, float],
    dict[str, float],
    pd.DataFrame,
    dict[str, np.ndarray],
]:
    """
    Evaluate each file independently and aggregate their results.

    Returns:
        macro_metrics:
            Unweighted mean of the per-file metrics.
        micro_metrics:
            Metrics over all query predictions pooled together.
        per_file_metrics:
            One metric row per file.
        predictions_by_file:
            Predictions indexed by filename.
    """
    if not episodes:
        raise ValueError("No evaluation episodes were provided.")

    per_file_rows = []
    predictions_by_file = {}
    all_true_values = []
    all_predictions = []

    # Evaluate each file separately
    for file_name, episode in episodes.items():
        memory_stage("evaluating file", report=True, file=file_name)
        file_metrics, file_predictions = evaluate_episode(
            model,
            tokenizer,
            episode,
            device,
            model_dtype,
        )

        true_values = episode.y_query.iloc[:, 0].to_numpy(
            dtype=float
        )

        per_file_rows.append(
            {
                "source_file": file_name,
                **file_metrics,
            }
        )

        predictions_by_file[file_name] = file_predictions
        all_true_values.append(true_values)
        all_predictions.append(file_predictions)

    memory_stage("aggregating evaluation metrics", file="-")
    per_file_metrics = pd.DataFrame(per_file_rows)

    # Macro: every file receives equal weight.
    macro_metrics = {
        metric: float(per_file_metrics[metric].mean(skipna=True))
        for metric in ["MAE", "RMSE", "R2"]
    }

    # Micro: every masked query value receives equal weight.
    # file B has ten times as many query values as file A -> B has approx ten times as much influence on micro MAE.
    micro_metrics = regression_metrics(
        np.concatenate(all_true_values),
        np.concatenate(all_predictions),
    )

    return (
        macro_metrics,
        micro_metrics,
        per_file_metrics,
        predictions_by_file,
    )


def fit_lora(
    regressor: SAP_RPT_OSS_Regressor,
    train_frames: dict[str, pd.DataFrame],
    fixed_validation_episodes: dict[str, Episode],
    training_seed: int = BASE_SEED,
) -> tuple[
    pd.DataFrame,
    dict[str, torch.Tensor],
    dict[str, float],
    dict[str, float],
    pd.DataFrame,
]:
    """
    - One training file is selected per optimization step.
    - A dynamically masked episode is created from only that file.
    - The checkpoint with the lowest macro validation MAE is retained. (Each file is treated equally)
    - Early stopping also depends on macro validation MAE.
    """
    model = regressor.model
    device = regressor.device
    model_dtype = regressor.dtype

    if not train_frames:
        raise ValueError("No training files were provided.")

    if not fixed_validation_episodes:
        raise ValueError("No validation episodes were provided.")

    training_tokenizer = make_tokenizer(is_valid=False)
    validation_tokenizer = make_tokenizer(is_valid=True)

    optimizer = torch.optim.AdamW(
        trainable_parameters(model),
        lr=LEARNING_RATE,
        weight_decay=WEIGHT_DECAY,
    )

    # Mixed precision training
    use_fp16_scaler = (device.type == "cuda" and model_dtype == torch.float16)
    scaler = torch.amp.GradScaler("cuda", enabled=use_fp16_scaler,)

    # Should be equivalent to the pretrained SAP RPT model
    memory_stage("initial validation", report=True, phase="initial validation", step="-")
    (initial_validation_macro, initial_validation_micro, _, _,) = evaluate_episode_group(
        model,
        validation_tokenizer,
        fixed_validation_episodes,
        device,
        model_dtype,
    )

    # Checkpoint selection is based on macro validation MAE.
    best_validation_mae = initial_validation_macro["MAE"]
    best_state = trainable_state_dict(model)
    validations_without_improvement = 0
    history = []

    print(
        "Initial macro validation metrics:",
        initial_validation_macro,
    )
    print(
        "Initial micro validation metrics:",
        initial_validation_micro,
    )

    train_file_names = list(train_frames.keys())
    training_rng = np.random.default_rng(training_seed)
    current_file_order = []

    for step in range(1, FT_STEPS + 1):
        position_in_cycle = (
            (step - 1) % len(train_file_names)
        )

        # Shuffle the file order at the start of every cycle.
        # Every file is used once before a file is reused.
        if position_in_cycle == 0:
            current_file_order = training_rng.permutation(
                train_file_names
            ).tolist()

        train_file = current_file_order[position_in_cycle]
        train_data = train_frames[train_file]
        memory_stage("starting training step", phase="training", step=step, file=train_file)

        # One training file per step
        training_episode = make_episode(
            train_data,
            seed=training_seed + 10_000 + step, # new target mask generated per training step
        )

        batch = tokenize_episode(
            training_tokenizer,
            training_episode,
            device,
            model_dtype,
            include_labels=True,
        )

        optimizer.zero_grad(set_to_none=True)
        model.train()

        amp_context = (
            torch.autocast(
                device_type="cuda",
                dtype=model_dtype,
            )
            if device.type == "cuda"
            else nullcontext()
        )

        with amp_context:
            # During training, the outputs are predictions, loss, and R²
            memory_stage("training forward")
            _, loss, train_r2 = model(**batch)

        memory_stage("checking training loss")
        if not torch.isfinite(loss):
            raise FloatingPointError(
                f"Non-finite loss at step {step}: {loss}"
            )

        memory_stage("training backward")
        if use_fp16_scaler:
            scaler.scale(loss).backward()
            scaler.unscale_(optimizer)

            torch.nn.utils.clip_grad_norm_(
                trainable_parameters(model),
                GRADIENT_CLIP,
            )

            memory_stage("optimizer step")
            scaler.step(optimizer)
            scaler.update()
        else:
            loss.backward()

            torch.nn.utils.clip_grad_norm_(
                trainable_parameters(model),
                GRADIENT_CLIP,
            )

            memory_stage("optimizer step")
            optimizer.step()

        record = {
            "step": step,
            "train_file": train_file,
            "train_loss": float(loss.detach().cpu()),
            "train_normalized_R2": float(
                train_r2.detach().cpu()
            ),
        }

        if step % VALIDATE_EVERY == 0 or step == FT_STEPS:
            memory_stage("validation during training", report=True, phase="validation")
            (validation_macro, validation_micro, _, _,) = evaluate_episode_group(
                model,
                validation_tokenizer,
                fixed_validation_episodes,
                device,
                model_dtype,
            )

            record.update(
                {
                    f"validation_macro_{metric}": value
                    for metric, value in validation_macro.items()
                }
            )
            record.update(
                {
                    f"validation_micro_{metric}": value
                    for metric, value in validation_micro.items()
                }
            )

            print(
                f"step={step:4d} "
                f"file={train_file} "
                f"loss={record['train_loss']:.4f} "
                f"validation_macro_MAE="
                f"{validation_macro['MAE']:.4f} "
                f"validation_micro_MAE="
                f"{validation_micro['MAE']:.4f}"
            )

            # Select the checkpoint using macro validation MAE.
            if validation_macro["MAE"] < best_validation_mae:
                best_validation_mae = validation_macro["MAE"]
                best_state = trainable_state_dict(model)
                validations_without_improvement = 0
            else:
                validations_without_improvement += 1

            if (validations_without_improvement >= EARLY_STOPPING_PATIENCE):
                print(f"Early stopping at step {step}.")
                history.append(record)
                break

        history.append(record)

    # Restore the checkpoint with the lowest macro validation MAE.
    memory_stage("restoring best adapter", report=True, phase="best validation", step="-", file="-")
    load_trainable_state_dict(model, best_state)

    (best_validation_macro, best_validation_micro, best_validation_per_file, _,) = evaluate_episode_group(
        model,
        validation_tokenizer,
        fixed_validation_episodes,
        device,
        model_dtype,
    )

    return (
        pd.DataFrame(history),
        best_state,
        best_validation_macro,
        best_validation_micro,
        best_validation_per_file,
    )


def validate_lora_training_setup(
    model: nn.Module,
    expected_device: torch.device | str,
) -> None:
    expected_device = torch.device(expected_device)
    if (
        expected_device.type == "cuda"
        and expected_device.index is None
    ):
        expected_device = torch.device(
            "cuda",
            torch.cuda.current_device(),
        )

    trainable = [
        (name, parameter)
        for name, parameter in model.named_parameters()
        if parameter.requires_grad
    ]

    if not trainable:
        raise RuntimeError("The model has no trainable parameters.")

    problems: list[str] = []

    for name, parameter in trainable:
        if parameter.device != expected_device:
            problems.append(
                f"{name}: device={parameter.device}; "
                f"expected={expected_device}"
            )

        if parameter.dtype != torch.float32:
            problems.append(
                f"{name}: dtype={parameter.dtype}; "
                "expected=torch.float32"
            )

    if problems:
        raise RuntimeError(
            "Invalid LoRA training configuration:\n"
            + "\n".join(problems)
        )

    print(
        f"Validated {len(trainable)} trainable FP32 parameters "
        f"on {expected_device}."
    )

