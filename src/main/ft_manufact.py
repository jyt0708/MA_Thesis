def _read_memory_text(path):
    try:
        return Path(path).read_text().strip()
    except (OSError, ValueError):
        return None


def _gib(value):
    if value is None:
        return "unavailable"
    if value == "max":
        return "unlimited"
    try:
        number = int(value)
        # cgroup v1 uses a huge integer to mean effectively unlimited.
        return "unlimited" if number >= 2**60 else f"{number / 2**30:.3f} GiB"
    except (TypeError, ValueError):
        return "unavailable"


def _proc_memory_fields(path):
    result = {}
    for line in (_read_memory_text(path) or "").splitlines():
        name, _, value = line.partition(":")
        parts = value.split()
        if len(parts) == 2 and parts[1] == "kB":
            result[name] = int(parts[0]) * 1024
    return result


def _find_memory_cgroups():
    """Find visible v1/v2 memory cgroups, including limiting ancestors.

    Use mount roots as well as membership paths for Enroot/cgroup namespaces.
    Ancestors hidden by a container cannot be inspected from inside it.
    """
    groups = []
    memberships = (_read_memory_text("/proc/self/cgroup") or "").splitlines()
    mounts = (_read_memory_text("/proc/self/mountinfo") or "").splitlines()
    for membership in memberships:
        _, controllers, group_path = membership.split(":", 2)
        version = 2 if not controllers else 1
        if version == 1 and "memory" not in controllers.split(","):
            continue
        for mount in mounts:
            left, separator, right = mount.partition(" - ")
            if not separator:
                continue
            fields, filesystem = left.split(), right.split()
            if version == 2 and filesystem[0] != "cgroup2":
                continue
            if version == 1 and (
                filesystem[0] != "cgroup" or "memory" not in filesystem[2].split(",")
            ):
                continue
            def unescape(value):
                for escaped, plain in [("\\040", " "), ("\\011", "\t"), ("\\012", "\n"), ("\\134", "\\")]:
                    value = value.replace(escaped, plain)
                return value
            mount_root = Path(unescape(fields[3]))
            mount_point = Path(unescape(fields[4]))
            membership_path = Path(group_path)
            try:
                relative = membership_path.relative_to(mount_root)
            except ValueError:
                # Membership may already be relative to a cgroup namespace.
                relative = Path(group_path.lstrip("/"))
            if ".." in relative.parts:
                continue
            current = mount_point / relative
            usage_name = "memory.current" if version == 2 else "memory.usage_in_bytes"
            while True:
                if (current / usage_name).is_file() and (version, current) not in groups:
                    groups.append((version, current))
                if current == mount_point:
                    break
                current = current.parent
    return groups


def report_memory(reason="snapshot", *, include_cuda=True, detailed=False):
    """Best-effort diagnostics; never replace the original training error."""
    try:
        state = _MEMORY_STATE.copy()
        lines = [
            f"[MEMORY {time.strftime('%Y-%m-%d %H:%M:%S')}] {reason} "
            f"pid={os.getpid()} " + " ".join(f"{key}={value}" for key, value in state.items())
        ]
        process = _proc_memory_fields("/proc/self/status")
        host = _proc_memory_fields("/proc/meminfo")
        lines.append(
            f"  CPU process: RSS={_gib(process.get('VmRSS'))}; "
            f"peak_RSS={_gib(process.get('VmHWM'))}; swap={_gib(process.get('VmSwap'))}"
        )
        lines.append(
            f"  Host RAM (not the job allocation): available={_gib(host.get('MemAvailable'))}; "
            f"total={_gib(host.get('MemTotal'))}"
        )
        if not _MEMORY_CGROUPS:
            lines.append("  Cgroup RAM: unavailable inside this environment; check Slurm sacct.")
        for version, directory in _MEMORY_CGROUPS:
            names = (
                ("memory.current", "memory.peak", "memory.max", "memory.events")
                if version == 2 else
                ("memory.usage_in_bytes", "memory.max_usage_in_bytes", "memory.limit_in_bytes", "memory.failcnt")
            )
            used, peak, limit, events = [_read_memory_text(directory / name) for name in names]
            lines.append(
                f"  Cgroup v{version} {directory}: used={_gib(used)}; "
                f"peak={_gib(peak)}; limit={_gib(limit)}; "
                f"events/failcnt={(events or 'unavailable').replace(chr(10), ', ')}"
            )
        # Print CPU information first, in case the CUDA driver itself fails.
        print("\n".join(lines), file=sys.stderr, flush=True)
        torch_module = sys.modules.get("torch")
        cuda = getattr(torch_module, "cuda", None)
        if include_cuda and cuda is not None and cuda.is_initialized():
            for index in range(cuda.device_count()):
                try:
                    print(
                        f"  GPU {index}: allocated={_gib(cuda.memory_allocated(index))}; "
                        f"reserved={_gib(cuda.memory_reserved(index))}; "
                        f"peak_allocated={_gib(cuda.max_memory_allocated(index))}; "
                        f"peak_reserved={_gib(cuda.max_memory_reserved(index))}",
                        file=sys.stderr, flush=True,
                    )
                    free, total = cuda.mem_get_info(index)
                    print(
                        f"  GPU {index} device-wide: free={_gib(free)}; total={_gib(total)}",
                        file=sys.stderr, flush=True,
                    )
                    if detailed:
                        print(cuda.memory_summary(device=index, abbreviated=True), file=sys.stderr, flush=True)
                except Exception as diagnostic_error:
                    print(f"  GPU {index} diagnostics unavailable: {diagnostic_error}", file=sys.stderr, flush=True)
        elif include_cuda:
            print("  GPU: PyTorch CUDA not initialized; diagnostics did not initialize it.", file=sys.stderr, flush=True)
    except Exception as diagnostic_error:
        try:
            print(f"[MEMORY] Diagnostics unavailable: {diagnostic_error}", file=sys.stderr, flush=True)
        except Exception:
            pass


def memory_stage(stage, *, report=False, **details):
    """Update the operation label; sample GPU memory on the main thread."""
    global _MEMORY_LAST_MAIN_REPORT
    _MEMORY_STATE.update(stage=stage, **details)
    now = time.monotonic()
    if report or now - _MEMORY_LAST_MAIN_REPORT >= MEMORY_LOG_INTERVAL_SECONDS:
        _MEMORY_LAST_MAIN_REPORT = now
        report_memory("stage")


def _memory_watchdog():
    # CPU/cgroup-only sampling avoids touching CUDA from the monitor thread.
    while not _MEMORY_STOP.wait(MEMORY_LOG_INTERVAL_SECONDS):
        report_memory("periodic", include_cuda=False)


def _memory_excepthook(exception_type, exception, traceback):
    _MEMORY_STOP.set()
    try:
        report_memory(f"UNHANDLED {exception_type.__name__}: {exception}", detailed=True)
    finally:
        # Keep the full original traceback and Python's nonzero exit status.
        sys.__excepthook__(exception_type, exception, traceback)


def stop_memory_monitor():
    _MEMORY_STOP.set()
    if _MEMORY_THREAD is not None:
        _MEMORY_THREAD.join(timeout=1.0)


