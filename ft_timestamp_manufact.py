def is_datetime_column(column_name: str) -> bool:
    """Case-insensitive name matching; existence indicators remain numeric."""
    name = str(column_name).casefold()
    return not name.endswith("__exists") and ("date" in name or "time" in name)


def parse_datetime_column(values: pd.Series, source_name: str) -> pd.Series:
    """Parse full timestamps without dropping clock time or subsecond values.

    European dates are day-first; year-first dates are parsed year-first.
    Time-only strings use TIME_ORIGIN's calendar date (never today's date).
    Blank/null features stay NaT. Nonempty invalid values raise with examples;
    numeric epochs/durations are rejected because their units are unknown.
    """
    text = values.astype("string").str.strip()
    missing = text.isna() | text.str.casefold().isin(
        ["", "nan", "nat", "none", "null", "<na>", "n/a"]
    )
    parsed_by_text = {}
    bad_values = []
    for value in text[~missing].unique():
        try:
            # reject plain numbers
            if re.fullmatch(r"[+-]?\d+(?:\.\d+)?", value):
                raise ValueError("Numeric timestamps need an explicit unit")
            candidate = value

            # give time-only strings a fixed date by attaching reference date
            if re.fullmatch(r"\d{1,2}:\d{2}(?::\d{2}(?:\.\d+)?)?", value):
                candidate = f"{TIME_ORIGIN.date()} {value}"

            # require 4-digit year
            elif not re.search(r"\d{4}", value):
                raise ValueError("A full date must include a four-digit year")

            year_first = bool(re.match(r"^\d{4}[-/]", candidate))
            timestamp = pd.Timestamp(pd.to_datetime(
                candidate, dayfirst=not year_first, errors="raise"
            ))
            if pd.isna(timestamp):
                raise ValueError("Nonempty value parsed as NaT")
            if timestamp.tzinfo is None:
                timestamp = timestamp.tz_localize(
                    NAIVE_DATETIME_TIMEZONE,
                    ambiguous="raise", nonexistent="raise",
                )
            parsed_by_text[value] = timestamp.tz_convert("UTC")
        except (ValueError, TypeError, OverflowError) as exc:
            bad_values.append((value, str(exc)))
    if bad_values:
        raise ValueError(
            f"{source_name}: cannot parse {len(bad_values)} distinct date/time "
            f"values. Examples: {bad_values[:5]}. Numeric date/time columns "
            "need an explicit epoch unit or duration policy."
        )
    return pd.Series(
        [pd.NaT if is_missing else parsed_by_text[value]
         for value, is_missing in zip(text, missing)],
        index=values.index, name=values.name, dtype="datetime64[ns, UTC]",
    )


def datetime_to_seconds(values: pd.Series) -> pd.Series:
    """Full elapsed seconds, including days and any fractional second."""
    return (values - TIME_ORIGIN).dt.total_seconds().astype("float64")


def seconds_to_datetime(values):
    return TIME_ORIGIN + pd.to_timedelta(
        np.asarray(values, dtype=np.float64), unit="s"
    )


