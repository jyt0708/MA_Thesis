def target_reference_columns() -> tuple[str, ...]:
    columns = {
        "fixed_origin": (),
        "first_event": (FIRST_EVENT_COLUMN,),
        "last_event": (LAST_EVENT_COLUMN,),
        "midpoint": (FIRST_EVENT_COLUMN, LAST_EVENT_COLUMN),
    }
    if TARGET_REPRESENTATION not in columns:
        raise ValueError(f"Unknown TARGET_REPRESENTATION: {TARGET_REPRESENTATION!r}")
    required = columns[TARGET_REPRESENTATION]
    if TARGET_COLUMN in required:
        raise ValueError("The target itself cannot be its reference column.")
    return required


def target_reference_time(frame: pd.DataFrame) -> pd.Series:
    """Use TIME_ORIGIN for missing reference timestamps."""
    required = target_reference_columns()
    references = {}

    for column in required:
        if column not in frame.columns:
            raise KeyError(
                f"{TARGET_REPRESENTATION} requires column {column!r}"
            )

        values = frame[column]
        if not pd.api.types.is_datetime64_any_dtype(values.dtype):
            raise TypeError(
                f"{column!r} must be parsed as a datetime column first"
            )

        references[column] = values.fillna(TIME_ORIGIN)

    if TARGET_REPRESENTATION == "fixed_origin":
        return pd.Series(
            TIME_ORIGIN,
            index=frame.index,
            dtype="datetime64[ns, UTC]",
        )

    if TARGET_REPRESENTATION == "first_event":
        return references[FIRST_EVENT_COLUMN]

    if TARGET_REPRESENTATION == "last_event":
        return references[LAST_EVENT_COLUMN]

    # For midpoint, use TIME_ORIGIN if either endpoint is missing.
    first = frame[FIRST_EVENT_COLUMN]
    last = frame[LAST_EVENT_COLUMN]
    missing = first.isna() | last.isna()

    if ((last < first) & ~missing).any():
        raise ValueError(
            "Cannot form midpoint: last_event_time precedes first_event_time"
        )

    midpoint = first + (last - first) / 2
    return midpoint.fillna(TIME_ORIGIN)


def encode_target_seconds(frame: pd.DataFrame) -> pd.Series:
    """Model target: signed seconds relative to the selected reference."""
    return (frame[TARGET_COLUMN] - target_reference_time(frame)).dt.total_seconds().astype("float64")


def restore_timestamp_seconds(values, reference_seconds) -> np.ndarray:
    """Return original timestamp seconds since TIME_ORIGIN for metrics/export."""
    values = np.asarray(values, dtype=np.float64).reshape(-1)
    reference_seconds = np.asarray(reference_seconds, dtype=np.float64).reshape(-1)
    if values.shape != reference_seconds.shape:
        raise ValueError("Prediction/reference row counts differ")
    if not (np.isfinite(values).all() and np.isfinite(reference_seconds).all()):
        raise ValueError("Prediction/reference contains non-finite values")
    return values + reference_seconds


