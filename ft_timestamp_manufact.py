@torch.no_grad()
def check_validation_precision(regressor, episodes, label, output_dir=None):
    """Compare current inference precision with FP32 on identical validation data.

    Uses a model copy and tokenizes each episode only once. The training model,
    optimizer, episode masks, and checkpoint selection are not modified.
    FP32 uses the existing checkpoint values; it cannot recover weight precision
    already lost before this diagnostic.
    """
    device = torch.device(regressor.device)
    cuda_devices = []
    if device.type == "cuda":
        cuda_devices = [
            device.index if device.index is not None
            else torch.cuda.current_device()
        ]

    python_rng = random.getstate()
    numpy_rng = np.random.get_state()
    old_matmul_precision = torch.get_float32_matmul_precision()
    old_cudnn_tf32 = torch.backends.cudnn.allow_tf32
    diagnostic_model = None
    tokenizer = None
    prepared = {}
    records = {}
    mode_summaries = []

    try:
        # Extra diagnostics must not advance the training RNG streams.
        with torch.random.fork_rng(devices=cuda_devices):
            diagnostic_model = copy.deepcopy(regressor.model).eval()
            tokenizer = make_tokenizer(is_valid=True)

            # One tokenization per episode; both passes use copies of these data.
            for file_name, episode in episodes.items():
                batch_cpu = tokenize_episode(
                    tokenizer, episode, torch.device("cpu"), torch.float32,
                    include_labels=False,
                )
                _, mean, std = tokenizer.standard_scale_column(
                    episode.y_context, episode.y_query,
                )
                prepared[file_name] = (
                    batch_cpu, float(mean), float(std),
                    # >>> TARGET REPRESENTATION: metrics on original timestamps.
                    episode.query_timestamp_seconds,
                    episode.query_reference_seconds,
                    # <<< TARGET REPRESENTATION
                )
                records[file_name] = {
                    "stage": label,
                    "target_representation": TARGET_REPRESENTATION,
                    "source_file": file_name,
                    "context_rows": len(episode.X_context),
                    "query_rows": len(episode.X_query),
                    "regressor_dtype": str(regressor.dtype),
                    "target_std_seconds": float(std),
                    "target_std_days": float(std) / 86400,
                    "error_if_z_off_by_0_001_minutes": float(std) * 0.001 / 60,
                }

            for mode, dtype in [("current", regressor.dtype), ("fp32", torch.float32)]:
                if mode == "fp32":
                    diagnostic_model.float()
                    # Disable reduced-precision FP32 matmul and convolution.
                    torch.set_float32_matmul_precision("highest")
                    torch.backends.cudnn.allow_tf32 = False

                parameter_dtypes = ", ".join(sorted({
                    str(p.dtype) for p in diagnostic_model.parameters()
                    if p.is_floating_point()
                }))
                all_true, all_pred, file_metrics = [], [], []

                for file_name, (batch_cpu, mean, std, true, reference_seconds) in prepared.items():
                    batch = to_device(
                        copy.deepcopy(batch_cpu), device, dtype=dtype,
                        raise_on_unexpected=False,
                    )
                    with torch.autocast(device_type=device.type, enabled=False):
                        outputs = diagnostic_model(**batch)
                    query_mask = batch["data"]["target"] <= -99
                    z = outputs[query_mask].detach().reshape(-1).cpu()
                    z64 = z.to(torch.float64)
                    pred = z64.numpy() * std + mean
                    # >>> TARGET REPRESENTATION: restore after inverse scaling.
                    pred = restore_timestamp_seconds(pred, reference_seconds)
                    # <<< TARGET REPRESENTATION
                    metrics = regression_metrics(true, pred)

                    # Adjacent representable output values, expressed in seconds.
                    # This is numerical spacing, NOT measured prediction error.
                    next_z = torch.nextafter(z, torch.full_like(z, float("inf")))
                    spacing_seconds = (
                        (next_z.to(torch.float64) - z64).abs().numpy() * abs(std)
                    )

                    row = records[file_name]
                    row[f"{mode}_parameter_dtypes"] = parameter_dtypes
                    row[f"{mode}_target_tensor_dtype"] = str(batch["data"]["target"].dtype)
                    row[f"{mode}_output_dtype"] = str(outputs.dtype)
                    row[f"{mode}_MAE_hours"] = metrics["MAE"] / 3600
                    row[f"{mode}_RMSE_hours"] = metrics["RMSE"] / 3600
                    row[f"{mode}_Within_3600s_percent"] = metrics["Within_3600s_percent"]
                    row[f"{mode}_output_spacing_median_seconds"] = float(np.median(spacing_seconds))
                    if mode == "current":
                        row["_current_predictions"] = pred.copy()
                    else:
                        difference = np.abs(pred - row.pop("_current_predictions"))
                        row["prediction_difference_mean_hours"] = float(difference.mean()) / 3600
                        row["MAE_improvement_hours"] = row["current_MAE_hours"] - row["fp32_MAE_hours"]

                    file_metrics.append(metrics)
                    all_true.append(true)
                    all_pred.append(pred)
                    del batch, outputs, query_mask, z, z64, next_z

                pooled = regression_metrics(np.concatenate(all_true), np.concatenate(all_pred))
                mode_summaries.append({
                    "stage": label,
                    "target_representation": TARGET_REPRESENTATION,
                    "precision": mode,
                    "input_dtype": str(dtype),
                    "parameter_dtypes": parameter_dtypes,
                    "macro_MAE_hours": float(np.mean([m["MAE"] for m in file_metrics])) / 3600,
                    "micro_MAE_hours": pooled["MAE"] / 3600,
                    "micro_RMSE_hours": pooled["RMSE"] / 3600,
                    "micro_Within_3600s_percent": pooled["Within_3600s_percent"],
                })
    finally:
        torch.set_float32_matmul_precision(old_matmul_precision)
        torch.backends.cudnn.allow_tf32 = old_cudnn_tf32
        random.setstate(python_rng)
        np.random.set_state(numpy_rng)
        del diagnostic_model, tokenizer
        prepared.clear()
        gc.collect()
        if device.type == "cuda":
            torch.cuda.empty_cache()

    details = pd.DataFrame(records.values())
    summary = pd.DataFrame(mode_summaries)
    print(f"\n[PRECISION CHECK] {label} | configured dtype: {regressor.dtype}")
    print(summary.to_string(index=False))
    print(details[[
        "source_file", "target_std_days", "error_if_z_off_by_0_001_minutes",
        "current_output_dtype", "fp32_output_dtype",
        "current_MAE_hours", "fp32_MAE_hours", "MAE_improvement_hours",
        "current_output_spacing_median_seconds", "prediction_difference_mean_hours",
    ]].to_string(index=False))

    if output_dir is not None:
        output_dir = Path(output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)
        details.to_csv(output_dir / f"precision_{label}_per_file.csv", index=False)
        summary.to_csv(output_dir / f"precision_{label}_summary.csv", index=False)
    return details, summary


def check_saved_fold_precision(fold=1):
    """Optional: check an existing fold checkpoint without rerunning training.

    Run the existing setup/data/function cells and the diagnostic helper cell,
    then call this function instead of executing the original training loop.
    Use the same configuration and source CSVs as the saved experiment.
    """
    fold_dir = OUTPUT_DIR / f"fold_{fold}"
    safe_target = TARGET_COLUMN.replace(" ", "_").replace("/", "_")
    checkpoint_path = fold_dir / f"{DOMAIN}_{safe_target}_lora_adapter.pt"
    checkpoint = torch.load(checkpoint_path, map_location="cpu", weights_only=True)
    if checkpoint["target_column"] != TARGET_COLUMN:
        raise ValueError("Checkpoint target differs from the configured target.")

    # >>> TARGET REPRESENTATION: do not load an adapter for a different target.
    validate_checkpoint_target_representation(checkpoint)
    # <<< TARGET REPRESENTATION

    if checkpoint["time_origin"] != TIME_ORIGIN.isoformat():
        raise ValueError("Use the same TIME_ORIGIN as the saved experiment.")

    episodes = {
        name: make_episode(frames[name], seed=BASE_SEED + 100 * fold + 1000 + i)
        for i, name in enumerate(checkpoint["validation_files"])
    }
    diagnostic_regressor = SAP_RPT_OSS_Regressor(
        max_context_size=MAX_CONTEXT_SIZE, bagging=BAGGING,
    )
    try:
        baseline = check_validation_precision(
            diagnostic_regressor, episodes, "pretrained_validation", fold_dir,
        )
        inject_lora(
            diagnostic_regressor.model,
            rank=checkpoint["lora_rank"], alpha=checkpoint["lora_alpha"],
            dropout=checkpoint["lora_dropout"],
        )
        load_trainable_state_dict(diagnostic_regressor.model, checkpoint["adapter_state_dict"])
        adapted = check_validation_precision(
            diagnostic_regressor, episodes, "lora_validation", fold_dir,
        )
        return {"pretrained": baseline, "lora": adapted}
    finally:
        del diagnostic_regressor
        gc.collect()
        if torch.cuda.is_available():
            torch.cuda.empty_cache()
# <<< PRECISION CHECK

"""### 1.4 Inject LoRA and fine tune

SAP RPT's fit() stores in-context examples; it does not
perform gradient-based fine-tuning.

-> Train the underlying PyTorch model through its differentiable forward pass.

(Evaluate the model before inserting lora for comparison, or just use the initial evaluation result?)


"""

fold_metrics_rows = []
fold_test_predictions = []
fold_comparison_rows = []

for split in fold_splits:
    fold = split["fold"]
    fold_seed = BASE_SEED + 100 * fold
    set_seed(fold_seed)

    fold_output_dir = OUTPUT_DIR / f"fold_{fold}"
    fold_output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    # Keep every training file separate
    train_frames = {
        file_name: frames[file_name]
        for file_name in split["train_files"]
    }

    # Create a fixed episode for each validation file
    validation_episodes = {
        file_name: make_episode(
            frames[file_name],
            seed=fold_seed + 1_000 + file_index,
        )
        for file_index, file_name
        in enumerate(split["validation_files"])
    }

    # Create a fixed episode for each test file
    test_episodes = {
        file_name: make_episode(
            frames[file_name],
            seed=fold_seed + 2_000 + file_index,
        )
        for file_index, file_name
        in enumerate(split["test_files"])
    }

    print(f"\n===== Fold {fold}/{N_FOLDS} =====")
    print("Training files:", split["train_files"])
    print("Validation files:", split["validation_files"])
    print("Test files:", split["test_files"])

    print("\nTraining file rows:")
    for file_name, frame in train_frames.items():
        print(f"  {file_name}: {len(frame)}")

    # context size / query size
    print("\nValidation context/query:")
    for file_name, episode in validation_episodes.items():
        print(
            f"  {file_name}: "
            f"{len(episode.X_context)}/"
            f"{len(episode.X_query)}"
        )

    print("\nTest context/query:")
    for file_name, episode in test_episodes.items():
        print(
            f"  {file_name}: "
            f"{len(episode.X_context)}/"
            f"{len(episode.X_query)}"
        )

    # Model is created per fold
    regressor = SAP_RPT_OSS_Regressor(
        max_context_size=MAX_CONTEXT_SIZE,
        bagging=BAGGING,
    )
    model = regressor.model

    # Paired baseline: evaluate the untouched pretrained model on the same
    # fixed test episodes that will later evaluate the best LoRA model.
    pretrained_evaluation_tokenizer = make_tokenizer(is_valid=True)

    (
        pretrained_test_macro,
        pretrained_test_micro,
        pretrained_test_per_file,
        pretrained_test_predictions_by_file,
    ) = evaluate_episode_group(
        model,
        pretrained_evaluation_tokenizer,
        test_episodes,
        regressor.device,
        regressor.dtype,
    )

    # Test results are recorded only for the final paired comparison.
    print("Pretrained test macro metrics:", pretrained_test_macro)
    print("Pretrained test micro metrics:", pretrained_test_micro)

    # >>> PRECISION CHECK: pretrained model, fixed validation episodes only
    if RUN_PRECISION_CHECK:
        check_validation_precision(
            regressor, validation_episodes,
            label="pretrained_validation", output_dir=fold_output_dir,
        )
    # <<< PRECISION CHECK

    replaced_modules = inject_lora(model)

    trainable_count = sum(
        parameter.numel()
        for parameter in trainable_parameters(model)
    )
    total_count = sum(
        parameter.numel()
        for parameter in model.parameters()
    )

    print(
        f"Inserted {len(replaced_modules)} LoRA adapters."
    )
    print(
        f"Trainable parameters: "
        f"{trainable_count:,} / {total_count:,} "
        f"({100 * trainable_count / total_count:.6f}%)"
    )

    validate_lora_training_setup(regressor.model, regressor.device)

    (history, best_adapter_state, best_validation_macro, best_validation_micro, validation_per_file_metrics) = fit_lora(
        regressor,
        train_frames,
        validation_episodes,
        training_seed=fold_seed,
    )

    # >>> PRECISION CHECK: fit_lora has restored the best validation checkpoint
    if RUN_PRECISION_CHECK:
        check_validation_precision(
            regressor, validation_episodes,
            label="lora_validation", output_dir=fold_output_dir,
        )
    # <<< PRECISION CHECK

    history.to_csv(fold_output_dir / "training_history.csv",index=False)

    validation_per_file_metrics.insert(0, "fold", fold)
    validation_per_file_metrics.to_csv(
        fold_output_dir
        / "per_file_validation_metrics.csv",
        index=False,
    )

    # Evaluate every test file independently.
    evaluation_tokenizer = make_tokenizer(is_valid=True)

    (test_macro_metrics, test_micro_metrics, test_per_file_metrics, test_predictions_by_file) = evaluate_episode_group(
        model,
        evaluation_tokenizer,
        test_episodes,
        regressor.device,
        regressor.dtype,
    )

    test_per_file_metrics.insert(0, "fold", fold)
    test_per_file_metrics.to_csv(
        fold_output_dir / "per_file_test_metrics.csv",
        index=False,
    )

    pretrained_test_per_file.insert(0, "fold", fold)
    pretrained_test_per_file.to_csv(
        fold_output_dir / "pretrained_per_file_test_metrics.csv",
        index=False,
    )

    pretrained_per_file_for_comparison = pretrained_test_per_file.rename(
        columns={
            "MAE": "pretrained_MAE",
            "RMSE": "pretrained_RMSE",
            "R2": "pretrained_R2",
        }
    )
    lora_per_file_for_comparison = test_per_file_metrics.rename(
        columns={
            "MAE": "lora_MAE",
            "RMSE": "lora_RMSE",
            "R2": "lora_R2",
        }
    )
    per_file_comparison = pretrained_per_file_for_comparison.merge(
        lora_per_file_for_comparison,
        on=["fold", "source_file"],
        validate="one_to_one",
    )
    per_file_comparison["MAE_improvement"] = (
        per_file_comparison["pretrained_MAE"]
        - per_file_comparison["lora_MAE"]
    )
    per_file_comparison["RMSE_improvement"] = (
        per_file_comparison["pretrained_RMSE"]
        - per_file_comparison["lora_RMSE"]
    )
    per_file_comparison["R2_improvement"] = (
        per_file_comparison["lora_R2"]
        - per_file_comparison["pretrained_R2"]
    )
    per_file_comparison["MAE_improvement_percent"] = np.where(
        per_file_comparison["pretrained_MAE"] != 0,
        100
        * per_file_comparison["MAE_improvement"]
        / per_file_comparison["pretrained_MAE"],
        np.nan,
    )
    per_file_comparison.to_csv(
        fold_output_dir / "pretrained_vs_lora_per_file_metrics.csv",
        index=False,
    )

    # Build the row-level test prediction table.
    test_prediction_tables = []

    for file_name, file_predictions in (
        test_predictions_by_file.items()
    ):
        episode = test_episodes[file_name]

        # >>> TARGET REPRESENTATION: predictions are already restored by evaluation.
        true_values = episode.query_timestamp_seconds
        # <<< TARGET REPRESENTATION
        pretrained_file_predictions = np.asarray(
            pretrained_test_predictions_by_file[file_name],
            dtype=float,
        ).reshape(-1)
        lora_file_predictions = np.asarray(
            file_predictions,
            dtype=float,
        ).reshape(-1)

        if not (
            len(true_values)
            == len(pretrained_file_predictions)
            == len(lora_file_predictions)
        ):
            raise ValueError(
                f"Prediction length mismatch for {file_name}: "
                f"true={len(true_values)}, "
                f"pretrained={len(pretrained_file_predictions)}, "
                f"LoRA={len(lora_file_predictions)}"
            )

        test_prediction_tables.append(
            pd.DataFrame(
                {
                    "fold": fold,
                    "source_file": file_name,
                    # Index in the filtered file.
                    "filtered_row_index": episode.query_indices,
                    f"true_{TARGET_COLUMN}": true_values,
                    "pretrained_prediction": pretrained_file_predictions,
                    "lora_prediction": lora_file_predictions,
                    "target_unit": TARGET_UNIT,
                    # >>> TARGET REPRESENTATION: numeric predictions keep their old meaning.
                    "target_representation": TARGET_REPRESENTATION,
                    "prediction_representation": "fixed_origin",
                    "reference_timestamp_UTC": seconds_to_datetime(episode.query_reference_seconds),
                    # <<< TARGET REPRESENTATION
                    "true_timestamp_UTC": seconds_to_datetime(true_values),
                    "pretrained_timestamp_UTC": seconds_to_datetime(pretrained_file_predictions),
                    "lora_timestamp_UTC": seconds_to_datetime(lora_file_predictions),
                    "pretrained_absolute_error_seconds": np.abs(
                        true_values - pretrained_file_predictions
                    ),
                    "lora_absolute_error_seconds": np.abs(
                        true_values - lora_file_predictions
                    ),
                    "pretrained_absolute_error": np.abs(
                        true_values - pretrained_file_predictions
                    ),
                    "lora_absolute_error": np.abs(
                        true_values - lora_file_predictions
                    ),
                }
            )
        )

    test_predictions = pd.concat(
        test_prediction_tables,
        axis=0,
        ignore_index=True,
    )

    # Positive values mean that LoRA improved baseline
    test_predictions["absolute_error_improvement"] = (
        test_predictions["pretrained_absolute_error"]
        - test_predictions["lora_absolute_error"]
    )

    test_predictions.to_csv(
        fold_output_dir / "test_predictions.csv",
        index=False,
    )
    fold_test_predictions.append(test_predictions)

    file_columns = {
        "train_files": "|".join(split["train_files"]),
        "validation_files": "|".join(
            split["validation_files"]
        ),
        "test_files": "|".join(split["test_files"]),
    }

    # Save both macro and micro metrics. Pretrained and LoRA test rows
    # use identical files, masks, and query values.
    for model_name, split_name, aggregation, values in [
        ("Pretrained", "test", "macro", pretrained_test_macro),
        ("Pretrained", "test", "micro", pretrained_test_micro),
        ("LoRA", "validation", "macro", best_validation_macro),
        ("LoRA", "validation", "micro", best_validation_micro),
        ("LoRA", "test", "macro", test_macro_metrics),
        ("LoRA", "test", "micro", test_micro_metrics),
    ]:
        fold_metrics_rows.append(
            {
                "fold": fold,
                "model": model_name,
                "split": split_name,
                "aggregation": aggregation,
                **file_columns,
                **values,
            }
        )

    for aggregation, pretrained_metrics, lora_metrics in [
        ("macro", pretrained_test_macro, test_macro_metrics),
        ("micro", pretrained_test_micro, test_micro_metrics),
    ]:
        mae_improvement = pretrained_metrics["MAE"] - lora_metrics["MAE"]
        rmse_improvement = pretrained_metrics["RMSE"] - lora_metrics["RMSE"]
        r2_improvement = lora_metrics["R2"] - pretrained_metrics["R2"]
        fold_comparison_rows.append(
            {
                "fold": fold,
                "aggregation": aggregation,
                "pretrained_MAE": pretrained_metrics["MAE"],
                "lora_MAE": lora_metrics["MAE"],
                "MAE_improvement": mae_improvement,
                "MAE_improvement_percent": (
                    100 * mae_improvement / pretrained_metrics["MAE"]
                    if pretrained_metrics["MAE"] != 0
                    else float("nan")
                ),
                "pretrained_RMSE": pretrained_metrics["RMSE"],
                "lora_RMSE": lora_metrics["RMSE"],
                "RMSE_improvement": rmse_improvement,
                "pretrained_R2": pretrained_metrics["R2"],
                "lora_R2": lora_metrics["R2"],
                "R2_improvement": r2_improvement,
                "LoRA_improved_MAE": mae_improvement > 0,
            }
        )

    safe_target_name = (TARGET_COLUMN.replace(" ", "_").replace("/", "_"))

    # Save the lora checkpoint
    torch.save(
        {
            "fold": fold,
            "train_files": split["train_files"],
            "validation_files":
                split["validation_files"],
            "test_files": split["test_files"],
            "target_column": TARGET_COLUMN,
            "target_unit": TARGET_UNIT,
            # >>> TARGET REPRESENTATION: required when reloading this adapter.
            "target_representation": TARGET_REPRESENTATION,
            "target_reference_columns": list(target_reference_columns()),
            "metrics_representation": "fixed_origin",
            # <<< TARGET REPRESENTATION
            "time_origin": TIME_ORIGIN.isoformat(),
            "naive_datetime_timezone": NAIVE_DATETIME_TIMEZONE,
            "datetime_features": [
                "hour", "minute", "second", "elapsed_seconds"
            ],
            "lora_rank": LORA_RANK,
            "lora_alpha": LORA_ALPHA,
            "lora_dropout": LORA_DROPOUT,
            "replaced_modules": replaced_modules,
            "adapter_state_dict": best_adapter_state,
            "validation_macro_metrics":
                best_validation_macro,
            "validation_micro_metrics":
                best_validation_micro,
            "pretrained_test_macro_metrics":
                pretrained_test_macro,
            "pretrained_test_micro_metrics":
                pretrained_test_micro,
            "test_macro_metrics":
                test_macro_metrics,
            "test_micro_metrics":
                test_micro_metrics,
        },
        fold_output_dir
        / f"{DOMAIN}_{safe_target_name}_lora_adapter.pt",
    )

    print(
        "Best macro validation metrics:",
        best_validation_macro,
    )
    print(
        "Test macro metrics:",
        test_macro_metrics,
    )
    print(
        "Test micro metrics:",
        test_micro_metrics,
    )
    print(
        "Macro test MAE improvement (positive = LoRA better):",
        pretrained_test_macro["MAE"] - test_macro_metrics["MAE"],
    )
    print(
        "Micro test MAE improvement (positive = LoRA better):",
        pretrained_test_micro["MAE"] - test_micro_metrics["MAE"],
    )

    del model, regressor, best_adapter_state
    gc.collect()

    if torch.cuda.is_available():
        torch.cuda.empty_cache()

