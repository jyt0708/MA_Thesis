@dataclass
class Episode:
    X_context: pd.DataFrame
    y_context: pd.DataFrame
    X_query: pd.DataFrame
    y_query: pd.DataFrame
    query_indices: np.ndarray
    # >>> TARGET REPRESENTATION: metadata only, never passed as model features.
    query_reference_seconds: np.ndarray  # reference time (in seconds)
    query_timestamp_seconds: np.ndarray  # true target time (in seconds)
    # <<< TARGET REPRESENTATION


def split_xy(frame: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    # hide target-leaking columns and the target column
    feature_drop = ["object_id", TARGET_COLUMN]
    if TARGET_COLUMN in ("obj_attr__yyy__timestamp", "obj_attr__xxx__timestamp"):
        # The parent JSON contains the timestamp being predicted.
        feature_drop.append(TARGET_COLUMN.rsplit("__", 1)[0])
    X = frame.drop(columns=feature_drop, errors="ignore").copy()

    # >>> TARGET REPRESENTATION: same feature columns; only y is re-encoded.
    y = pd.DataFrame({
        TARGET_COLUMN: encode_target_seconds(frame)
    }, index=frame.index)
    # <<< TARGET REPRESENTATION

    # add extra numeric features since SAP RPT’s built-in tokenizer ignores clock time
    X = add_datetime_features(X)

    if X.empty:
        raise ValueError("No feature columns remain after leakage removal.")
    return X, y


def make_episode(
    frame: pd.DataFrame,
    seed: int,
    missing_rate = MISSING_RATE,
    max_context_size = MAX_CONTEXT_SIZE,
    query_cap: int | None = QUERY_CAP,
) -> Episode:
    '''Create one within-file missing-value prediction episode.'''
    if not 0 < missing_rate < 1:
        raise ValueError("missing_rate must be between 0 and 1.")

    rng = np.random.default_rng(seed)
    n_rows = len(frame)
    query_size = max(1, int(round(n_rows * missing_rate)))
    if query_cap is not None:
        query_size = min(query_size, query_cap)
    query_size = min(query_size, n_rows - 1)

    all_positions = np.arange(n_rows)
    query_positions = np.sort(
        rng.choice(all_positions, size=query_size, replace=False)
    )
    context_positions = np.setdiff1d(
        all_positions, query_positions, assume_unique=True
    )

    # sample again if context size is too large
    if len(context_positions) > max_context_size:
        context_positions = np.sort(
            rng.choice(
                context_positions,
                size=max_context_size,
                replace=False,
            )
        )

    context_frame = frame.iloc[context_positions].reset_index(drop=True)
    query_frame = frame.iloc[query_positions].reset_index(drop=True)
    X_context, y_context = split_xy(context_frame)
    X_query, y_query = split_xy(query_frame)

    if list(X_context.columns) != list(X_query.columns):
        raise AssertionError("Context/query feature schemas differ.")

    return Episode(
        X_context=X_context,
        y_context=y_context,
        X_query=X_query,
        y_query=y_query,
        query_indices=query_positions,
        # >>> TARGET REPRESENTATION:
        query_reference_seconds=datetime_to_seconds(
            target_reference_time(query_frame)
        ).to_numpy(dtype=np.float64),
        query_timestamp_seconds=datetime_to_seconds(
            query_frame[TARGET_COLUMN]
        ).to_numpy(dtype=np.float64),
        # <<< TARGET REPRESENTATION
    )


