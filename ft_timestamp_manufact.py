def add_datetime_features(X: pd.DataFrame) -> pd.DataFrame:
    """Keep native datetime features and expose all components numerically.

    Called only after removing the prediction target.
    SAP RPT's native date encoding omits clock time, these numeric
    features preserve hour/minute/second information for it.
    """
    X = X.copy()
    datetime_columns = [
        c for c in X.columns if pd.api.types.is_datetime64_any_dtype(X[c].dtype)
    ]
    for c in datetime_columns:
        values = X[c]
        components = {
            "hour": values.dt.hour,
            "minute": values.dt.minute,
            "second": (values.dt.second + values.dt.microsecond / 1e6
                       + values.dt.nanosecond / 1e9),
            "elapsed_seconds": datetime_to_seconds(values),
        }
        for component, numeric_values in components.items():
            name = f"{c}__dt_{component}"
            if name in X.columns:
                raise ValueError(f"Generated datetime feature already exists: {name}")
            X[name] = numeric_values.astype("float64")
    return X


