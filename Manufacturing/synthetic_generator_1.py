class _Rng:
    def __init__(self, seed: int) -> None:
        self._s = seed & 0xFFFFFFFFFFFFFFFF

    def _n(self) -> int:
        self._s = (self._s * 6364136223846793005 + 1442695040888963407) & 0xFFFFFFFFFFFFFFFF
        return self._s

    def random(self) -> float:
        return (self._n() >> 11) / float(1 << 53)

    def randint(self, a: int, b: int) -> int:
        if b < a:
            raise ValueError("randint empty range")
        return a + int(self.random() * (b - a + 1)) % (b - a + 1)

    def choice(self, seq: Sequence[Any]) -> Any:
        return seq[self.randint(0, len(seq) - 1)]

    def uniform(self, a: float, b: float) -> float:
        return a + (b - a) * self.random()

    def gauss(self, mu: float, sigma: float) -> float:
        u1 = max(self.random(), 1e-12)
        u2 = self.random()
        z = math.sqrt(-2.0 * math.log(u1)) * math.cos(2 * math.pi * u2)
        return mu + sigma * z

    def hex(self, n: int) -> str:
        chars = "0123456789abcdef"
        return "".join(chars[self.randint(0, 15)] for _ in range(n))

    def uuid(self) -> str:
        return f"{self.hex(8)}-{self.hex(4)}-{self.hex(4)}-{self.hex(4)}-{self.hex(12)}"


