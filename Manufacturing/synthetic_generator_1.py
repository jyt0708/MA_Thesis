    def fetch_loop(self, sub: str, component: str, n_recv: int, part: Dict[str, Any], noisy: bool = False) -> None:
        base = "Fetch"
        act = self.add_act(base)
        extra = self.comp[component]
        t0 = self.now
        self.emit(base, "activity/calling", self.bump(), sub, act, extra=extra, endpoint=EP["fetch"])
        for i in range(n_recv):
            self.emit(base, "activity/receiving", self.bump(0.08, 0.25), sub, act, extra=extra, endpoint=EP["fetch"], data=self.snapshot([_nv("fetch", True), _nv("event_batch", i)]))
            if component == "MaxxTurn45":
                if i == 0:
                    kind = "empty"
                elif i == 1:
                    kind = "partial"
                else:
                    kind = "full"
                self.lathe_stream(self.now, part, kind)
            else:
                if i == 0:
                    kind = "empty"
                elif i == 1:
                    kind = "partial"
                else:
                    kind = "full"
                self.keyence_stream(self.now, kind, noisy)
        self.emit(base, "activity/done", self.bump(), sub, act, extra=extra, endpoint=EP["fetch"])
        self.poll_windows.append(("Fetch", t0, self.now))

