    def sample_batch(self) -> None:
        n = self.n
        items = [SOURCE_ITEMS[i % len(SOURCE_ITEMS)] for i in range(n)]
        orders: Dict[str, List[str]] = {}
        pattern = [5, 3]
        i = 0
        oi = 1
        while i < n:
            take = min(pattern[(oi - 1) % 2], n - i)
            orders[f"order{oi}"] = items[i : i + take]
            i += take
            oi += 1
        self.orders = orders
        remaining = []
        for oid in orders:
            remaining.extend([(oid, it) for it in orders[oid]])
        for k in range(n):
            order_id, item = remaining[k]
            if n == 8 and k in SOURCE_PARAMS:
                initial, order_id, item, fd, tray = SOURCE_PARAMS[k]
                feed, depth = fd
            else:
                initial = k == 0
                tray = _tray_xyz(k)
                if item == "wr04":
                    feed = self.rng.choice([0.03, 0.03, 0.03, 0.07])
                    depth = self.rng.choice([0.4, 0.6])
                else:
                    feed = 0.05
                    depth = self.rng.choice([0.2, 0.4, 0.6])
            suffix = remaining[k + 1 :]
            self.parts.append(
                {
                    "count": k,
                    "order_id": order_id,
                    "order_item": item,
                    "initial": initial,
                    "current_tray": tray,
                    "program_params": [feed, depth, f"{order_id}: {item}"],
                    "order_list": [[a, b] for a, b in suffix],
                    "feed": feed,
                    "depth": depth,
                }
            )

